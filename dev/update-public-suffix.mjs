// Build-time only. The installed extension never fetches this list.
// Run: node dev/update-public-suffix.mjs [path-to-public_suffix_list.dat]
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { domainToASCII } from 'node:url';

const source = 'https://publicsuffix.org/list/public_suffix_list.dat';
let input;
if (process.argv[2]) {
  input = await readFile(process.argv[2], 'utf8');
} else {
  const response = await fetch(source, { signal: AbortSignal.timeout(30000), redirect: 'error' });
  if (!response.ok) throw new Error(`PSL download failed: ${response.status}`);
  input = await response.text();
}
if (input.length > 2000000 || !input.includes('// ===END PRIVATE DOMAINS===')) {
  throw new Error('Incomplete or oversized Public Suffix List');
}
const rules = input.split(/\r?\n/).map((s) => s.trim()).filter((s) => s && !s.startsWith('//'));
const normalized = rules.map((rule) => {
  const prefix = rule.startsWith('!') ? '!' : rule.startsWith('*.') ? '*.' : '';
  const host = domainToASCII(rule.slice(prefix.length));
  if (!host || !/^[a-z0-9.-]+$/.test(host)) throw new Error('Invalid PSL rule');
  return prefix + host;
});
if (normalized.length < 9000) throw new Error('Unexpectedly small Public Suffix List');
const metadata = {
  source,
  version: input.match(/^\/\/ VERSION: (.+)$/m)?.[1] ?? null,
  commit: input.match(/^\/\/ COMMIT: (.+)$/m)?.[1] ?? null,
  sha256: createHash('sha256').update(input).digest('hex'),
  ruleCount: normalized.length
};
const output = `// Generated by dev/update-public-suffix.mjs. Do not edit by hand.
// Public Suffix List, including ICANN and PRIVATE sections.
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.
export const PSL_METADATA = ${JSON.stringify(metadata, null, 2)};
export const PUBLIC_SUFFIX_RULES = ${JSON.stringify([...new Set(normalized)].sort(), null, 2)};
`;
await writeFile(new URL('../data/public-suffix-rules.js', import.meta.url), output);
console.log(`Bundled ${metadata.ruleCount} PSL rules; source SHA-256 ${metadata.sha256}`);
